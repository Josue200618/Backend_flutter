CREATE SCHEMA IF NOT EXISTS lacombalpalo;
SET search_path TO lacombalpalo, public;

CREATE TABLE IF NOT EXISTS roles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(45) NOT NULL UNIQUE,
    description VARCHAR(100) NOT NULL DEFAULT '',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    is_system BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
ALTER TABLE roles ADD COLUMN IF NOT EXISTS is_system BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS privilegios (
    id_privilegio INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_privilegio VARCHAR(45) NOT NULL UNIQUE,
    descripcion VARCHAR(100) NOT NULL DEFAULT '',
    estado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS permisos (
    id_permiso INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_permiso VARCHAR(45) NOT NULL,
    codigo VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(100) NOT NULL DEFAULT '',
    CONSTRAINT permisos_nombre_unique UNIQUE (nombre_permiso)
);

CREATE TABLE IF NOT EXISTS asignacion_rol (
    id_asignacion_rol INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rol_id INTEGER NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    permiso_id INTEGER NOT NULL REFERENCES permisos(id_permiso) ON DELETE CASCADE,
    privilegio_id INTEGER NOT NULL REFERENCES privilegios(id_privilegio),
    CONSTRAINT asignacion_rol_permission_unique UNIQUE (rol_id, permiso_id)
);

CREATE TABLE IF NOT EXISTS usuario (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    roles_idroles INTEGER NOT NULL REFERENCES roles(id),
    tipo_identificacion VARCHAR(25),
    identificacion VARCHAR(45) NOT NULL DEFAULT '',
    primer_nombre VARCHAR(60) NOT NULL DEFAULT '',
    segundo_nombre VARCHAR(60),
    primer_apellido VARCHAR(60) NOT NULL DEFAULT '',
    segundo_apellido VARCHAR(60),
    nombre_completo VARCHAR(160) NOT NULL,
    correo VARCHAR(254) NOT NULL,
    telefono VARCHAR(40) NOT NULL DEFAULT '',
    clave_hash TEXT NOT NULL,
    estado BOOLEAN NOT NULL DEFAULT TRUE,
    failed_login_attempts INTEGER NOT NULL DEFAULT 0 CHECK (failed_login_attempts >= 0),
    locked_until TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS usuario_correo_lower_idx ON usuario (LOWER(correo));

CREATE TABLE IF NOT EXISTS clientes (
    id_clientes INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER UNIQUE REFERENCES usuario(id_usuario) ON DELETE SET NULL,
    tipo_persona VARCHAR(45) NOT NULL DEFAULT 'natural',
    tipo_documento VARCHAR(30) NOT NULL DEFAULT 'otro',
    num_documento VARCHAR(45) NOT NULL,
    nombre_o_razon_social VARCHAR(160) NOT NULL,
    business_name VARCHAR(160),
    telefono VARCHAR(40) NOT NULL DEFAULT '',
    correo VARCHAR(254) NOT NULL,
    departamento VARCHAR(100) NOT NULL DEFAULT '',
    municipio VARCHAR(100) NOT NULL DEFAULT '',
    direccion_entrega VARCHAR(1000) NOT NULL DEFAULT '',
    estado BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT clientes_documento_unique UNIQUE (tipo_documento, num_documento)
);
CREATE INDEX IF NOT EXISTS clientes_nombre_idx ON clientes(nombre_o_razon_social);

CREATE TABLE IF NOT EXISTS categoria_producto (
    id_categoria_producto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_categoria VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(500) NOT NULL DEFAULT '',
    estado BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS productos (
    id_producto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_producto_id INTEGER NOT NULL REFERENCES categoria_producto(id_categoria_producto),
    sku VARCHAR(80) NOT NULL UNIQUE,
    nombre_producto VARCHAR(160) NOT NULL,
    descripcion VARCHAR(200) NOT NULL DEFAULT '',
    precio_base NUMERIC(10, 0) NOT NULL CHECK (precio_base >= 0),
    existencias INTEGER NOT NULL DEFAULT 0 CHECK (existencias >= 0),
    existencias_reservadas INTEGER NOT NULL DEFAULT 0
        CHECK (existencias_reservadas >= 0 AND existencias_reservadas <= existencias),
    stock_minimo INTEGER NOT NULL DEFAULT 0 CHECK (stock_minimo >= 0),
    estado BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
ALTER TABLE productos ADD COLUMN IF NOT EXISTS stock_minimo INTEGER NOT NULL DEFAULT 0;
CREATE INDEX IF NOT EXISTS productos_categoria_idx ON productos(categoria_producto_id);
CREATE INDEX IF NOT EXISTS productos_estado_idx ON productos(estado);

CREATE TABLE IF NOT EXISTS imagen_producto (
    id_imagen_producto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    productos_idproducto INTEGER NOT NULL REFERENCES productos(id_producto) ON DELETE CASCADE,
    url_imagen_producto VARCHAR(200) NOT NULL
);
CREATE INDEX IF NOT EXISTS imagen_producto_product_idx ON imagen_producto(productos_idproducto);

CREATE TABLE IF NOT EXISTS proveedores (
    id_proveedores INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_de_documento VARCHAR(30) NOT NULL DEFAULT 'otro',
    num_documento VARCHAR(45) NOT NULL DEFAULT '',
    nombre VARCHAR(160) NOT NULL,
    telefono VARCHAR(40) NOT NULL DEFAULT '',
    correo VARCHAR(254) NOT NULL DEFAULT '',
    departamento VARCHAR(100) NOT NULL DEFAULT '',
    municipio VARCHAR(100) NOT NULL DEFAULT '',
    direccion VARCHAR(1000) NOT NULL DEFAULT '',
    estado BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT proveedores_documento_unique UNIQUE (tipo_de_documento, num_documento)
);

CREATE TABLE IF NOT EXISTS proveedor_producto (
    proveedor_id INTEGER NOT NULL REFERENCES proveedores(id_proveedores) ON DELETE CASCADE,
    producto_id INTEGER NOT NULL REFERENCES productos(id_producto) ON DELETE CASCADE,
    costo_adquisicion NUMERIC(12, 2) NOT NULL CHECK (costo_adquisicion >= 0),
    PRIMARY KEY (proveedor_id, producto_id)
);

CREATE TABLE IF NOT EXISTS compra (
    id_compra INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proveedores_idproveedores INTEGER NOT NULL REFERENCES proveedores(id_proveedores),
    fecha_compra TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    valor_total NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (valor_total >= 0),
    estado BOOLEAN NOT NULL DEFAULT TRUE,
    estado_compra VARCHAR(20) NOT NULL DEFAULT 'draft'
        CHECK (estado_compra IN ('draft', 'received', 'cancelled')),
    recibido_en TIMESTAMPTZ,
    created_by INTEGER REFERENCES usuario(id_usuario),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS detalle_compra (
    id_detalle_compra INTEGER GENERATED BY DEFAULT AS IDENTITY,
    compra_idcompra INTEGER NOT NULL REFERENCES compra(id_compra) ON DELETE CASCADE,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(12, 4) NOT NULL CHECK (precio_unitario >= 0),
    productos_idproducto INTEGER NOT NULL REFERENCES productos(id_producto),
    PRIMARY KEY (id_detalle_compra, productos_idproducto),
    CONSTRAINT detalle_compra_producto_unique UNIQUE (compra_idcompra, productos_idproducto)
);

CREATE TABLE IF NOT EXISTS pedido_venta (
    id_pedido INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clientes_idclientes INTEGER NOT NULL REFERENCES clientes(id_clientes),
    usuario_id INTEGER REFERENCES usuario(id_usuario),
    fecha TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    estado_pedido VARCHAR(45) NOT NULL DEFAULT 'pending'
        CHECK (estado_pedido IN ('pending', 'approved', 'rejected', 'cancelled', 'delivered')),
    valor_total NUMERIC(10, 2) NOT NULL CHECK (valor_total >= 0),
    metodo_pago VARCHAR(45) NOT NULL DEFAULT 'pendiente',
    comprobante_url TEXT,
    direccion_entrega VARCHAR(1000) NOT NULL DEFAULT '',
    notas TEXT,
    decidido_por INTEGER REFERENCES usuario(id_usuario),
    decidido_en TIMESTAMPTZ,
    entregado_en TIMESTAMPTZ,
    registrado_por INTEGER REFERENCES usuario(id_usuario),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
ALTER TABLE pedido_venta ADD COLUMN IF NOT EXISTS notas TEXT;
ALTER TABLE pedido_venta ADD COLUMN IF NOT EXISTS entregado_en TIMESTAMPTZ;
CREATE INDEX IF NOT EXISTS pedido_cliente_idx ON pedido_venta(clientes_idclientes, fecha DESC);
CREATE INDEX IF NOT EXISTS pedido_estado_idx ON pedido_venta(estado_pedido, fecha DESC);

CREATE TABLE IF NOT EXISTS detalle_pedido_venta (
    id_detalle_pedido INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id_pedido INTEGER NOT NULL REFERENCES pedido_venta(id_pedido) ON DELETE CASCADE,
    productos_idproducto INTEGER NOT NULL REFERENCES productos(id_producto),
    nombre_producto VARCHAR(160) NOT NULL,
    precio_unitario NUMERIC(10, 2) NOT NULL CHECK (precio_unitario >= 0),
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    CONSTRAINT detalle_pedido_producto_unique UNIQUE (pedido_id_pedido, productos_idproducto)
);

CREATE TABLE IF NOT EXISTS carritos (
    id_carrito INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL UNIQUE REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS detalle_carrito (
    id_detalle_carrito INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carrito_id INTEGER NOT NULL REFERENCES carritos(id_carrito) ON DELETE CASCADE,
    productos_idproducto INTEGER NOT NULL REFERENCES productos(id_producto),
    cantidad INTEGER NOT NULL CHECK (cantidad BETWEEN 1 AND 999),
    CONSTRAINT detalle_carrito_product_unique UNIQUE (carrito_id, productos_idproducto)
);

CREATE TABLE IF NOT EXISTS codigos_acceso (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
    codigo VARCHAR(10) NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    expira_en TIMESTAMPTZ NOT NULL,
    usado BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS auditoria (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER REFERENCES usuario(id_usuario) ON DELETE SET NULL,
    accion VARCHAR(80) NOT NULL,
    detalle TEXT,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS auditoria_fecha_idx ON auditoria(creado_en DESC);

CREATE TABLE IF NOT EXISTS venta_anulada (
    pedido_id INTEGER PRIMARY KEY REFERENCES pedido_venta(id_pedido) ON DELETE CASCADE,
    usuario_id INTEGER REFERENCES usuario(id_usuario) ON DELETE SET NULL,
    anulada_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public_migration_map (
    source_table VARCHAR(80) NOT NULL,
    source_id INTEGER NOT NULL,
    target_id INTEGER NOT NULL,
    PRIMARY KEY (source_table, source_id)
);

CREATE OR REPLACE VIEW permissions AS
    SELECT id_permiso AS id, codigo AS code, descripcion AS description
    FROM permisos;

CREATE OR REPLACE VIEW role_permissions AS
    SELECT rol_id AS role_id, permiso_id AS permission_id, privilegio_id AS privilege_id
    FROM asignacion_rol;

CREATE OR REPLACE VIEW users AS
    SELECT id_usuario AS id,
           roles_idroles AS role_id,
           correo AS email,
           clave_hash AS password_hash,
           nombre_completo AS full_name,
           primer_nombre AS first_name,
           segundo_nombre AS second_name,
           primer_apellido AS first_surname,
           segundo_apellido AS second_surname,
           telefono AS phone,
           identificacion AS identification,
           tipo_identificacion AS document_type,
           estado AS active,
           failed_login_attempts,
           locked_until,
           created_at,
           updated_at
    FROM usuario;

CREATE OR REPLACE VIEW customers AS
    SELECT id_clientes AS id,
           usuario_id AS user_id,
           nombre_o_razon_social AS name,
           business_name,
           num_documento AS identification,
           correo AS email,
           telefono AS phone,
           direccion_entrega AS address,
           estado AS active,
           tipo_persona AS person_type,
           tipo_documento AS document_type,
           departamento AS department,
           municipio AS municipality,
           created_at,
           updated_at
    FROM clientes;

CREATE OR REPLACE VIEW categories AS
    SELECT id_categoria_producto AS id,
           nombre_categoria AS name,
           descripcion AS description,
           estado AS active,
           created_at,
           updated_at
    FROM categoria_producto;

CREATE OR REPLACE VIEW products AS
    SELECT id_producto AS id,
           categoria_producto_id AS category_id,
           sku,
           nombre_producto AS name,
           descripcion AS description,
           precio_base AS price,
           existencias AS stock,
           existencias_reservadas AS reserved_stock,
           estado AS active,
           created_at,
           updated_at,
           stock_minimo
    FROM productos;

CREATE OR REPLACE VIEW suppliers AS
    SELECT id_proveedores AS id,
           nombre AS name,
           num_documento AS identification,
           correo AS email,
           telefono AS phone,
           direccion AS address,
           departamento AS department,
           municipio AS municipality,
           tipo_de_documento AS document_type,
           estado AS active,
           created_at,
           updated_at
    FROM proveedores;

CREATE OR REPLACE VIEW purchases AS
    SELECT id_compra AS id,
           proveedores_idproveedores AS supplier_id,
           created_by,
           estado_compra AS status,
           valor_total AS total,
           recibido_en AS received_at,
           fecha_compra AS created_at
    FROM compra;

CREATE OR REPLACE VIEW purchase_items AS
    SELECT id_detalle_compra AS id,
           compra_idcompra AS purchase_id,
           productos_idproducto AS product_id,
           cantidad AS quantity,
           precio_unitario AS unit_cost
    FROM detalle_compra;

CREATE OR REPLACE VIEW orders AS
    SELECT id_pedido AS id,
           clientes_idclientes AS customer_id,
           usuario_id AS user_id,
           estado_pedido AS status,
           direccion_entrega AS delivery_address,
           valor_total AS total,
           fecha AS created_at,
           updated_at,
           decidido_por AS decided_by,
           decidido_en AS decided_at,
           registrado_por AS recorded_by,
           notas,
           entregado_en AS delivered_at
    FROM pedido_venta;

CREATE OR REPLACE VIEW order_items AS
    SELECT id_detalle_pedido AS id,
           pedido_id_pedido AS order_id,
           productos_idproducto AS product_id,
           nombre_producto AS product_name,
           cantidad AS quantity,
           precio_unitario AS unit_price
    FROM detalle_pedido_venta;

CREATE OR REPLACE VIEW carts AS
    SELECT id_carrito AS id, usuario_id AS user_id, updated_at
    FROM carritos;

CREATE OR REPLACE VIEW cart_items AS
    SELECT id_detalle_carrito AS id,
           carrito_id AS cart_id,
           productos_idproducto AS product_id,
           cantidad AS quantity
    FROM detalle_carrito;

CREATE OR REPLACE VIEW sales AS
    SELECT id_pedido AS id,
           id_pedido AS order_id,
           valor_total AS total,
           fecha AS sold_at,
           registrado_por AS recorded_by,
           'active'::VARCHAR(20) AS status
    FROM pedido_venta
    WHERE estado_pedido = 'delivered'
    UNION ALL
    SELECT p.id_pedido,
           p.id_pedido,
           p.valor_total,
           p.fecha,
           p.registrado_por,
           'annulled'::VARCHAR(20)
    FROM pedido_venta p
    JOIN venta_anulada a ON a.pedido_id = p.id_pedido
    WHERE p.estado_pedido = 'approved';

CREATE OR REPLACE VIEW images AS
    SELECT id_imagen_producto AS id,
           productos_idproducto AS product_id,
           url_imagen_producto AS url
    FROM imagen_producto;

CREATE OR REPLACE VIEW api_roles AS
    SELECT id, name AS nombre, description AS descripcion, is_system AS es_sistema,
           active AS activo, created_at AS creado_en
    FROM roles;

CREATE OR REPLACE VIEW api_permissions AS
    SELECT id_permiso AS id, nombre_permiso AS nombre, codigo, descripcion
    FROM permisos;

CREATE OR REPLACE VIEW api_users AS
    SELECT id, full_name AS nombre, email AS correo, phone AS telefono,
           password_hash, role_id AS rol_id, active AS activo,
           failed_login_attempts AS intentos_fallidos, locked_until AS bloqueado_hasta,
           created_at AS creado_en
    FROM users;

CREATE OR REPLACE VIEW api_customers AS
    SELECT id, person_type AS tipo, name AS nombre, business_name AS razon_social,
           identification AS documento, phone AS telefono, email AS correo,
           address AS direccion, user_id AS usuario_id, active AS activo,
           created_at AS creado_en
    FROM customers;

CREATE OR REPLACE VIEW api_categories AS
    SELECT id, name AS nombre, description AS descripcion, active AS activo,
           created_at AS creado_en
    FROM categories;

CREATE OR REPLACE VIEW api_products AS
    SELECT id, category_id AS categoria_id, name AS nombre, description AS descripcion,
           sku, price AS precio, stock, stock_minimo, active AS activo,
           reserved_stock AS existencias_reservadas
    FROM products;

CREATE OR REPLACE VIEW api_suppliers AS
    SELECT id, name AS nombre, identification AS documento, email AS correo,
           phone AS telefono, address AS direccion, department AS departamento,
           municipality AS municipio, active AS activo
    FROM suppliers;

CREATE OR REPLACE VIEW api_purchases AS
    SELECT id, supplier_id AS proveedor_id, created_by AS usuario_id,
           created_at AS fecha,
           CASE status WHEN 'cancelled' THEN 'anulada' WHEN 'draft' THEN 'borrador' ELSE 'activa' END AS estado,
           total
    FROM purchases;

CREATE OR REPLACE VIEW api_purchase_items AS
    SELECT i.id, i.purchase_id AS compra_id, i.product_id AS producto_id,
           p.name AS nombre, i.quantity AS cantidad, i.unit_cost AS costo_unitario,
           i.quantity * i.unit_cost AS subtotal
    FROM purchase_items i
    JOIN products p ON p.id = i.product_id;

CREATE OR REPLACE VIEW api_orders AS
    SELECT id, customer_id AS cliente_id, user_id AS usuario_id,
           created_at AS fecha,
           CASE status
               WHEN 'pending' THEN 'pendiente'
               WHEN 'approved' THEN 'aprobado'
               WHEN 'rejected' THEN 'rechazado'
               WHEN 'cancelled' THEN 'cancelado'
               WHEN 'delivered' THEN 'entregado'
           END AS estado,
           total, delivery_address AS direccion_entrega, notas,
           decided_by AS aprobado_por, delivered_at AS entregado_en
    FROM orders;

CREATE OR REPLACE VIEW api_order_items AS
    SELECT i.id, i.order_id AS pedido_id, i.product_id AS producto_id,
           i.product_name AS nombre, i.unit_price AS precio_unitario,
           i.quantity AS cantidad, i.unit_price * i.quantity AS subtotal
    FROM order_items i;

CREATE OR REPLACE VIEW api_sales AS
    SELECT s.id, s.order_id AS pedido_id, o.customer_id AS cliente_id,
           o.user_id AS usuario_id, s.sold_at AS fecha, s.total,
           CASE s.status WHEN 'annulled' THEN 'anulada' ELSE 'activa' END AS estado,
           c.name AS cliente,
           c.identification AS documento
    FROM sales s
    JOIN orders o ON o.id = s.order_id
    JOIN customers c ON c.id = o.customer_id;

CREATE OR REPLACE VIEW api_sale_items AS
    SELECT i.id, i.order_id AS venta_id, i.product_id AS producto_id,
           i.product_name AS nombre, i.unit_price AS precio_unitario,
           i.quantity AS cantidad, i.unit_price * i.quantity AS subtotal
    FROM order_items i
    JOIN sales s ON s.order_id = i.order_id;
